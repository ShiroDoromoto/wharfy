package build

// oci.go — BYO-binary(依頼① #3)の OCI イメージ生成。GoReleaser の docker pipe(Go ビルド前提)を
// 使わず、docker buildx を subprocess で直叩きし、持ち込み linux バイナリからマルチアーキ OCI を
// build+push する(D-2)。version 注入はバイナリ側で済んでいる前提。
//
// 手順: 各 linux バイナリを .wharfy/dist/oci/<arch>/<binary> に整え、TARGETARCH で arch を選ぶ
// 単一 Dockerfile を書き、`buildx build --platform linux/amd64,linux/arm64 --push` で
// マニフェストリスト(:version と :latest)を一度に作る。
//
// レジストリ認証は RegistryLogin が受け持つ(push の前に docker login を打つ)。GoReleaser の
// docker pipe も docker の資格情報に乗るので、どちらの経路でも同じログインが効く。

import (
	"context"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// StdinRunner は stdin を流せるコマンド実行(--password-stdin 用・テストで差し替え)。
// Runner と別なのは、トークンを argv に載せない(ps に出さない)ため。
type StdinRunner func(ctx context.Context, stdin, name string, args ...string) ([]byte, error)

// RegistryLogin は push 先レジストリへの docker login。CI ではトークンを渡すだけで通るように、
// wharfy 自身がログインする(手元の docker が既に認証済みでも、渡されたトークンで上書きする
// ——利用者が wharfy に渡した資格情報こそが、wharfy の使うべき資格情報)。
type RegistryLogin struct {
	Bin      string // 既定 "docker"
	LookPath func(string) (string, error)
	Run      StdinRunner
}

// NewRegistryLogin は本番用(exec ベース)を差した実体を返す。
func NewRegistryLogin() *RegistryLogin {
	return &RegistryLogin{Bin: "docker", LookPath: exec.LookPath, Run: execRunStdin}
}

// Login は host に username/token でログインする。token が空なら何もしない(認証を要らない
// レジストリや、既存の資格情報に任せる経路を壊さないため)。
func (l *RegistryLogin) Login(ctx context.Context, host, username, token string) error {
	if token == "" {
		return nil
	}
	bin := l.Bin
	if bin == "" {
		bin = "docker"
	}
	if l.LookPath != nil {
		if _, err := l.LookPath(bin); err != nil {
			return &UnavailableError{Bin: bin, Err: err}
		}
	}
	out, err := l.Run(ctx, token, bin, "login", host, "-u", username, "--password-stdin")
	if err != nil {
		return &FailedError{Err: fmt.Errorf("docker login %s: %w", host, err), Output: tail(out, 2000)}
	}
	return nil
}

// RegistryHost は image 参照("ghcr.io/owner/name" 等)からレジストリのホストを取り出す。
// ホストらしさは最初のセグメントに "." か ":" が在ることで判る(無ければ Docker Hub の暗黙参照)。
func RegistryHost(image string) string {
	first, _, ok := strings.Cut(image, "/")
	if !ok || !strings.ContainsAny(first, ".:") {
		return "docker.io"
	}
	return first
}

// PrebuiltContainerizer は docker buildx で BYO の OCI イメージを作る(末端差し替え)。
type PrebuiltContainerizer struct {
	Bin      string // 既定 "docker"
	LookPath func(string) (string, error)
	Run      Runner
}

// NewPrebuiltContainerizer は本番用(exec ベース)を差した実体を返す。
func NewPrebuiltContainerizer() *PrebuiltContainerizer {
	return &PrebuiltContainerizer{Bin: "docker", LookPath: exec.LookPath, Run: execRun}
}

// PushMultiArch は image に :version と :latest のマルチアーキ OCI を build+push する。
// bins のうち linux のみを対象にする。返り値はエラーのみ(成果物は registry 上)。
func (b *PrebuiltContainerizer) PushMultiArch(ctx context.Context, root, distDir, image, version, binaryName string, bins []PrebuiltBinary) error {
	bin := b.Bin
	if bin == "" {
		bin = "docker"
	}
	if b.LookPath != nil {
		if _, err := b.LookPath(bin); err != nil {
			return &UnavailableError{Bin: bin, Err: err}
		}
	}

	// linux バイナリを arch ごとの決まった場所へ整える(Dockerfile が TARGETARCH で参照する)。
	var platforms []string
	stageRel := filepath.Join(distDir, "oci")
	for _, bl := range bins {
		if bl.OS != "linux" {
			continue
		}
		src := bl.Path
		if !filepath.IsAbs(src) {
			src = filepath.Join(root, bl.Path)
		}
		dstRel := filepath.Join(stageRel, bl.Arch, binaryName)
		if err := copyFile(src, filepath.Join(root, dstRel)); err != nil {
			return &FailedError{Err: fmt.Errorf("stage %s: %w", bl.Arch, err)}
		}
		platforms = append(platforms, "linux/"+bl.Arch)
	}
	if len(platforms) == 0 {
		return &FailedError{Err: fmt.Errorf("container: no linux binaries to package")}
	}

	dockerfileRel := filepath.Join(distDir, "oci.Dockerfile")
	df := ociDockerfile(stageRel, binaryName)
	if err := os.WriteFile(filepath.Join(root, dockerfileRel), []byte(df), 0o644); err != nil {
		return &FailedError{Err: fmt.Errorf("write Dockerfile: %w", err)}
	}

	args := []string{
		"buildx", "build",
		"--platform", strings.Join(platforms, ","),
		"-t", image + ":" + version,
		"-t", image + ":latest",
		"-f", dockerfileRel,
		"--push",
		".",
	}
	out, err := b.Run(ctx, root, bin, args...)
	if err != nil {
		return &FailedError{Err: fmt.Errorf("docker buildx: %w", err), Output: tail(out, 4000)}
	}
	return nil
}

// ociDockerfile は TARGETARCH で arch 別バイナリを選ぶ最小 Dockerfile を返す。
func ociDockerfile(stageRel, binaryName string) string {
	// stageRel は root 相対(ビルドコンテキストは root)。COPY は前方スラッシュで書く。
	stage := filepath.ToSlash(stageRel)
	return fmt.Sprintf(`# GENERATED BY wharfy — do not edit. BYO-binary OCI image (#3).
FROM scratch
ARG TARGETARCH
COPY %[1]s/${TARGETARCH}/%[2]s /usr/bin/%[2]s
ENTRYPOINT ["/usr/bin/%[2]s"]
`, stage, binaryName)
}

// copyFile は src を dst に複製する(実行ビットを保つ)。dst の親は作る。
func copyFile(src, dst string) error {
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return err
	}
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	out, err := os.OpenFile(dst, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o755)
	if err != nil {
		return err
	}
	if _, err := io.Copy(out, in); err != nil {
		out.Close()
		return err
	}
	return out.Close()
}

// script 有効時、生成 GoReleaser 設定の release.extra_files が install.sh を指す。
func TestGenerateGoReleaserScriptExtraFiles(t *testing.T) {
	data, err := GenerateGoReleaser(scriptConfig(), File{})
	if err != nil {
		t.Fatal(err)
	}
	var m map[string]any
	if err := yaml.Unmarshal(data, &m); err != nil {
		t.Fatal(err)
	}
	rel, ok := m["release"].(map[string]any)
	if !ok {
		t.Fatalf("release block missing: %v", m["release"])
	}
	extra, ok := rel["extra_files"].([]any)
	if !ok || len(extra) != 2 {
		t.Fatalf("extra_files should carry install.sh + install.ps1: %v", rel["extra_files"])
	}
	globs := map[string]bool{}
	for _, e := range extra {
		globs[e.(map[string]any)["glob"].(string)] = true
	}
	for _, want := range []string{".wharfy/install.sh", ".wharfy/install.ps1"} {
		if !globs[want] {
			t.Errorf("extra_files missing glob %q (have %v)", want, globs)
		}
	}
}

// script 無効時は extra_files を出さない。
